#!/usr/bin/env python3
"""Generate the host allowlist, independent Gradle graph and version defaults."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from android_plugin_catalog import (
    ROOT, SHARED_LIBRARIES, HOST_PACKAGE, MAX_JSON_BYTES, MAX_ERROR_CHARS,
    MAX_CONCURRENT_CALLS, INVOCATION_TIMEOUT_MS, TRANSPORT_TIMEOUT_MS,
    PluginCatalog, load_catalog,
)

HOST_CATALOG = Path("android/app/src/main/kotlin/com/github/lingyan000/fluxdo/OptionalPluginCatalog.kt")


def quote(value: str) -> str:
    # JSON and Kotlin share these escapes; Kotlin additionally interpolates $.
    return json.dumps(value, ensure_ascii=False).replace("$", r"\$")


def generated_files(catalog: PluginCatalog) -> dict[Path, str]:
    kotlin = '''// Generated from android_modular/plugins.json. Do not edit by hand.
package com.github.lingyan000.fluxdo

import android.content.ComponentName

internal data class OptionalPluginSpec(
    val id: String,
    val name: String,
    val packageName: String,
    val serviceClass: String,
    val operations: Set<String>,
    val activityClass: String? = null,
) {
    val component get() = ComponentName(packageName, serviceClass)
}

internal object OptionalPluginCatalog {
    val specs: List<OptionalPluginSpec> = listOf(
'''
    for spec in catalog.native:
        kotlin += "        OptionalPluginSpec(\n"
        for field in (spec.id, spec.name, spec.package, spec.service):
            kotlin += f"            {quote(field)},\n"
        kotlin += "            setOf(" + ", ".join(quote(op) for op in spec.operations) + "),\n"
        if spec.activity:
            kotlin += f"            {quote(spec.activity)},\n"
        kotlin += "        ),\n"
    sticker = catalog.plugin("sticker")
    kotlin += "    )\n"
    kotlin += f"    const val STICKER_PACKAGE = {quote(sticker.package)}\n"
    kotlin += f"    const val STICKER_ACTIVITY = {quote(sticker.activity)}\n}}\n"

    # A separate Gradle root: neither Flutter's plugin loader nor :app is
    # evaluated. Projects still share their original source and signing files.
    settings = '''// Generated from android_modular/plugins.json. Do not edit by hand.
pluginManagement {
    repositories {
        google()
        mavenCentral()
        gradlePluginPortal()
    }
}
plugins {
    id("com.android.application") version "8.11.1" apply false
    id("com.android.library") version "8.11.1" apply false
    id("org.jetbrains.kotlin.android") version "2.2.20" apply false
}
rootProject.name = "fluxdo-native-companions"
'''
    libraries = [lib for lib in SHARED_LIBRARIES if any(lib in p.libraries for p in catalog.native)]
    for module in libraries + [p.module for p in catalog.native]:
        settings += f'include(":{module}")\nproject(":{module}").projectDir = file("../{module}")\n'
    versions = "# Generated from android_modular/plugins.json. Do not edit by hand.\n"
    for spec in catalog.plugins:
        versions += f"{spec.id}.versionCode={spec.version_code}\n{spec.id}.versionName={spec.version_name}\n"
    dart = "// Generated from android_modular/plugins.json. Do not edit by hand.\n"
    dart += "import 'plugin_definition.dart';\n\n"
    dart += f"const pluginProtocolVersion = {catalog.protocol};\n"
    dart += f"const pluginMaxJsonBytes = {MAX_JSON_BYTES};\n"
    dart += f"const pluginMaxConcurrentCalls = {MAX_CONCURRENT_CALLS};\n"
    dart += f"const pluginTransportTimeout = Duration(milliseconds: {TRANSPORT_TIMEOUT_MS});\n\n"
    dart += "const androidPluginCatalog = <String, PluginDefinition>{\n"
    for spec in catalog.plugins:
        dart += f"  {quote(spec.id)}: PluginDefinition(\n"
        dart += f"    id: {quote(spec.id)},\n    name: {quote(spec.name)},\n"
        dart += f"    packageName: {quote(spec.package)},\n    runtime: PluginRuntime.{spec.kind},\n"
        dart += "    operations: {" + ", ".join(quote(op) for op in spec.operations) + "},\n"
        if spec.activity:
            dart += f"    activityClass: {quote(spec.activity)},\n"
        dart += "  ),\n"
    dart += "};\n"
    protocol = f'''// Generated by scripts/ci/generate_android_plugin_catalog.py. Do not edit by hand.
package {HOST_PACKAGE}.plugin.api

/** Stable cross-APK wire contract shared with fluxdo_plugin_contract. */
object PluginProtocol {{
    const val VERSION = {catalog.protocol}
    const val MAX_JSON_BYTES = {MAX_JSON_BYTES}
    const val MAX_ERROR_CHARS = {MAX_ERROR_CHARS}
    const val MAX_CONCURRENT_CALLS = {MAX_CONCURRENT_CALLS}
    const val INVOCATION_TIMEOUT_MS = {INVOCATION_TIMEOUT_MS}L
    const val CHANNEL = "{HOST_PACKAGE}/optional_plugins"
    const val BIND_PERMISSION = "{HOST_PACKAGE}.permission.BIND_PLUGIN"
    const val PROTOCOL_METADATA = "{HOST_PACKAGE}.plugin.PROTOCOL"

    const val REQUEST = 1
    const val RESPONSE = 2
    const val VERSION_KEY = "protocol"
    const val OPERATION_KEY = "operation"
    const val PAYLOAD_KEY = "payload"
    const val RESULT_KEY = "result"
    const val ERROR_KEY = "error"
}}
'''
    return {
        HOST_CATALOG: kotlin,
        Path("android/native_plugins/settings.gradle.kts"): settings,
        Path("android/plugin-versions.properties"): versions,
        Path("packages/fluxdo_plugin_contract/lib/src/catalog.g.dart"): dart,
        Path("android/plugin_api/src/main/kotlin/com/github/lingyan000/fluxdo/plugin/api/PluginProtocol.kt"): protocol,
    }


def synchronize(root: Path = ROOT, *, check: bool = False) -> None:
    files = generated_files(load_catalog(root / "android_modular/plugins.json"))
    stale = []
    for relative, content in files.items():
        path = root / relative
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        if check:
            stale.append(str(relative))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        raise RuntimeError("Stale plugin catalog outputs; run generator: " + ", ".join(stale))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    synchronize(check=parser.parse_args().check)
